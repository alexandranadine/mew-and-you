/**
 * Placeholder photos in our brand palette until real photos come from the API.
 * Swap `placeholderPhoto` usage for real adapter data once the backend is wired up.
 */
function placeholderPhoto(
  label: string,
  bg: string,
  fg: string,
): Cat["photos"] {
  const url = `https://placehold.co/640x480/${bg}/${fg}?font=playfair-display&text=${encodeURIComponent(label)}`;
  return [{ url, thumbnailUrl: url.replace("640x480", "320x240") }];
}

